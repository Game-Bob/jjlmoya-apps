import { afterEach, expect, it } from 'vitest';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, join, resolve } from 'node:path';
import { copyZtreakRuntime } from './copy-ztreak-runtime.mjs';

const roots = [];
function fixture() {
    const root = mkdtempSync(join(tmpdir(), 'ztreak-runtime-test-'));
    roots.push(root);
    const destination = join(root, 'public/assets/apps/ztreak/runtime');
    mkdirSync(destination, { recursive: true });
    return { root, destination };
}
afterEach(() => {
    for (const root of roots.splice(0)) {
        if (dirname(resolve(root)) !== resolve(tmpdir()) || !basename(root).startsWith('ztreak-runtime-test-')) throw new Error('Invalid fixture cleanup');
        rmSync(root, { recursive: true, force: true });
    }
});

it('preserves an existing directory that was not generated by this package', () => {
    const { root, destination } = fixture();
    const original = join(destination, 'manual.html');
    writeFileSync(original, 'Existing content');
    expect(() => copyZtreakRuntime(root)).toThrow('unrecognized runtime directory');
    expect(readFileSync(original, 'utf8')).toBe('Existing content');
});

it('replaces only a recognized generated runtime and excludes its cache from npm packaging', () => {
    const { root, destination } = fixture();
    writeFileSync(join(destination, '.ztreak-runtime.json'), JSON.stringify({ package: '@gamebob/ztreak', version: 'old' }));
    writeFileSync(join(destination, 'old-chunk.js'), 'stale');
    copyZtreakRuntime(root);
    expect(existsSync(join(destination, 'old-chunk.js'))).toBe(false);
    expect(readFileSync(join(destination, 'index.html'), 'utf8')).toContain('mountZtreak');
    expect(readFileSync(join(destination, '.npmignore'), 'utf8')).toBe('*\n');
    expect(JSON.parse(readFileSync(join(destination, '.ztreak-runtime.json'), 'utf8')).package).toBe('@gamebob/ztreak');
});
